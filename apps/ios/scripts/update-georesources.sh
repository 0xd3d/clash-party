#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP_RESOURCE_DIR="$ROOT_DIR/ClashParty/Resources/GeoResources"
TUNNEL_RESOURCE_DIR="$ROOT_DIR/ClashPartyTunnel/Resources/GeoResources"
MANIFEST_PATH="$ROOT_DIR/ClashPartyShared/Resources/GeoResources.manifest"
WORK_DIR="$(mktemp -d "${TMPDIR:-/tmp}/clashparty-georesources.XXXXXX")"

cleanup() {
  rm -rf "$WORK_DIR"
}
trap cleanup EXIT

declare -a RESOURCES=(
  "geoip-lite.dat|https://github.com/MetaCubeX/meta-rules-dat/releases/download/latest/geoip-lite.dat"
  "geosite.dat|https://github.com/MetaCubeX/meta-rules-dat/releases/download/latest/geosite.dat"
  "country-lite.mmdb|https://github.com/MetaCubeX/meta-rules-dat/releases/download/latest/country-lite.mmdb"
  "GeoLite2-ASN.mmdb|https://github.com/MetaCubeX/meta-rules-dat/releases/download/latest/GeoLite2-ASN.mmdb"
)

mkdir -p "$APP_RESOURCE_DIR" "$TUNNEL_RESOURCE_DIR" "$(dirname "$MANIFEST_PATH")"

for entry in "${RESOURCES[@]}"; do
  filename="${entry%%|*}"
  url="${entry#*|}"
  destination="$WORK_DIR/$filename"
  echo "Downloading $filename"
  curl -fL --retry 3 --retry-delay 2 "$url" -o "$destination"

  if [[ ! -s "$destination" ]]; then
    echo "Downloaded file is empty: $filename" >&2
    exit 1
  fi
done

for entry in "${RESOURCES[@]}"; do
  filename="${entry%%|*}"
  cp "$WORK_DIR/$filename" "$APP_RESOURCE_DIR/$filename"
  cp "$WORK_DIR/$filename" "$TUNNEL_RESOURCE_DIR/$filename"
done

{
  echo "# Generated by scripts/update-georesources.sh"
  echo "# Source: MetaCubeX/meta-rules-dat latest release"
  echo "# Updated: $(date -u +"%Y-%m-%dT%H:%M:%SZ")"
  echo
  for entry in "${RESOURCES[@]}"; do
    filename="${entry%%|*}"
    url="${entry#*|}"
    size="$(wc -c < "$WORK_DIR/$filename" | tr -d ' ')"
    sha256="$(shasum -a 256 "$WORK_DIR/$filename" | awk '{print $1}')"
    echo "$filename"
    echo "  url: $url"
    echo "  size: $size"
    echo "  sha256: $sha256"
  done
} > "$MANIFEST_PATH"

echo "Updated GeoResources:"
cat "$MANIFEST_PATH"
